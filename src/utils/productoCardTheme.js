function normalizeText(value) {
  return String(value || "")
    .normalize("NFD")
    .replace(/[\u0300-\u036f]/g, "")
    .trim()
    .toLowerCase();
}

function getHashIndex(value, length) {
  const normalized = normalizeText(value);

  if (!normalized || length <= 1) return 0;

  let hash = 0;
  for (let index = 0; index < normalized.length; index += 1) {
    hash = (hash * 31 + normalized.charCodeAt(index)) >>> 0;
  }

  return hash % length;
}

export function getProductoCardTheme(categoria, subcategoria, categoryColorKey = "") {
  const normalizedCategory = normalizeText(categoria);
  const resolvedCategory =
    CATEGORY_ALIASES[normalizedCategory] || normalizedCategory;
  const normalizedColorKey = normalizeText(categoryColorKey);
  const palette =
    CATEGORY_PALETTES[normalizedColorKey] ||
    CATEGORY_PALETTES[resolvedCategory] ||
    CATEGORY_PALETTES["productos varios"] ||
    DEFAULT_PALETTE;

  const colorSet = palette[getHashIndex(subcategoria, palette.length)];

  return {
    "--producto-card-bg": colorSet.background,
    "--producto-card-border": colorSet.border,
    "--producto-card-tag-bg": colorSet.tagBackground,
    "--producto-card-tag-color": colorSet.tagColor,
    "--producto-card-code-color": colorSet.codeColor,
    "--producto-card-accent": colorSet.border,
    "--producto-card-accent-soft": colorSet.tagBackground,
    "--producto-card-glow": `${colorSet.border}22`,
  };
}
